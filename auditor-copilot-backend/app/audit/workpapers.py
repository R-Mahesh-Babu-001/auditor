"""
Workpaper generation, versioning, and evidence verification service.
"""

import uuid
from datetime import datetime
from typing import Dict, Any, List, Optional
from sqlalchemy.orm import Session

from app.models import (
    AuditEngagement,
    AuditCriterion,
    AuditTestRun,
    AuditException,
    Workpaper,
    WorkpaperVersion,
    WorkpaperExceptionLink,
    WorkpaperEvidenceLink,
    EvidenceFile,
)
from app.llm.gemini import get_gemini_llm


def generate_structured_workpaper(
    db: Session,
    organization_id: uuid.UUID,
    engagement_id: uuid.UUID,
    title: str,
    workpaper_type: str = "p2p_testing_summary",
    objective_override: Optional[str] = None,
    user_id: Optional[uuid.UUID] = None,
) -> Dict[str, Any]:
    """Compile engagement evidence, criteria, and test outcomes into an evidence-linked audit workpaper."""
    engagement = db.query(AuditEngagement).filter(
        AuditEngagement.id == engagement_id,
        AuditEngagement.organization_id == organization_id,
    ).first()

    if not engagement:
        raise ValueError(f"Engagement {engagement_id} not found.")

    criteria = db.query(AuditCriterion).filter(
        AuditCriterion.engagement_id == engagement_id
    ).all()

    test_runs = db.query(AuditTestRun).filter(
        AuditTestRun.engagement_id == engagement_id,
        AuditTestRun.execution_status == "completed",
    ).order_by(AuditTestRun.created_at.desc()).all()

    exceptions = db.query(AuditException).filter(
        AuditException.engagement_id == engagement_id
    ).all()

    evidence_files = db.query(EvidenceFile).filter(
        EvidenceFile.engagement_id == engagement_id
    ).all()

    # Compile factual sections
    obj_text = objective_override or engagement.objective
    period_str = f"{engagement.period_start or 'N/A'} to {engagement.period_end or 'N/A'}"
    criteria_list = "\n".join([f"- [{c.criterion_code}] {c.title}: {c.requirement_text}" for c in criteria]) or "Standard IIA IPPF & COSO P2P control guidelines."
    
    test_summary_lines = []
    total_tested = 0
    total_exceptions = len(exceptions)
    for tr in test_runs:
        total_tested += tr.population_count
        test_summary_lines.append(f"- **Test {tr.rule_id}**: Tested {tr.population_count} items, {tr.passed_count} passed, {tr.exception_count} exceptions.")
    test_summary_text = "\n".join(test_summary_lines) if test_summary_lines else "No formal automated test runs executed yet."

    evidence_summary = "\n".join([f"- Evidence Ref [{f.id}]: {f.original_filename} ({f.evidence_category})" for f in evidence_files]) or "No source files attached."

    exceptions_summary = "\n".join([f"- Exception [{e.exception_key}] ({e.severity.upper()}): {e.title} - {e.description}" for e in exceptions[:10]]) or "Zero audit exceptions identified."

    conclusion = "Satisfactory with noted exceptions" if total_exceptions > 0 else "Satisfactory"

    # Draft markdown content
    markdown_content = f"""# Audit Workpaper: {title}
**Engagement:** {engagement.name} ({engagement.engagement_code})  
**Audit Period:** {period_str}  
**Date Prepared:** {datetime.utcnow().strftime('%Y-%m-%d')}  
**Status:** In Review  

---

## 1. Audit Objective
{obj_text}

## 2. Scope & Applicable Criteria
The scope covers operational disbursements and transactional integrity for business unit **{engagement.business_unit or 'Enterprise'}**.

**Applicable Criteria:**
{criteria_list}

## 3. Evidence & Data Sources Examined
{evidence_summary}

## 4. Audit Procedures & Testing Executed
{test_summary_text}

## 5. Exceptions & Deviations Identified
Total exceptions recorded: **{total_exceptions}**

{exceptions_summary}

## 6. Preliminary Auditor Assessment & Conclusion
**Conclusion:** {conclusion}

Based on the deterministic audit procedures performed on {total_tested} transactional records, the internal controls operated with the specific exceptions documented above. Management remediation is required for identified variances.

---
*Note: Generated by AuditReady Copilot with strict evidence linking. Unverified assertions require explicit human sign-off.*
"""

    # Persist workpaper and initial version in Neon DB
    code = f"WP-{title[:6].upper().replace(' ', '')}-{datetime.utcnow().strftime('%m%d')}"
    workpaper = Workpaper(
        organization_id=organization_id,
        engagement_id=engagement_id,
        workpaper_code=code,
        title=title,
        workpaper_type=workpaper_type,
        objective=obj_text,
        methodology="Deterministic P2P Testing with Gemini-assisted documentation",
        status="draft",
        created_by=user_id,
    )
    db.add(workpaper)
    db.flush()

    wp_version = WorkpaperVersion(
        organization_id=organization_id,
        engagement_id=engagement_id,
        workpaper_id=workpaper.id,
        version_number=1,
        content_markdown=markdown_content,
        structured_content={
            "objective": obj_text,
            "period": period_str,
            "total_tested": total_tested,
            "total_exceptions": total_exceptions,
            "conclusion": conclusion,
        },
        conclusion_status="satisfactory_with_exceptions" if total_exceptions > 0 else "satisfactory",
        generation_method="deterministic_synthesis",
        model_provider="gemini",
        model_name="gemini-3.5-flash",
        created_by=user_id,
        review_status="pending_review",
    )
    db.add(wp_version)
    db.flush()

    # Link exceptions
    for exc in exceptions[:50]:
        db.add(WorkpaperExceptionLink(
            organization_id=organization_id,
            engagement_id=engagement_id,
            workpaper_version_id=wp_version.id,
            exception_id=exc.id,
        ))

    # Link evidence
    for ef in evidence_files:
        db.add(WorkpaperEvidenceLink(
            organization_id=organization_id,
            engagement_id=engagement_id,
            workpaper_version_id=wp_version.id,
            evidence_file_id=ef.id,
            claim_or_section="Data Sources Examined",
            source_locator={"filename": ef.original_filename},
        ))

    db.commit()

    return {
        "status": "success",
        "workpaper_id": str(workpaper.id),
        "version_id": str(wp_version.id),
        "workpaper_code": workpaper.workpaper_code,
        "title": workpaper.title,
        "content_markdown": markdown_content,
    }

